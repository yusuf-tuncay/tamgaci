import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:tamgaci/features/inventory/domain/entities/inventory_movement.dart';

/// InventoryMovement model for Firebase integration
class InventoryMovementModel extends InventoryMovement {
  const InventoryMovementModel({
    required super.id,
    required super.movementNumber,
    required super.type,
    required super.status,
    required super.itemId,
    super.itemName,
    super.itemSku,
    required super.quantity,
    required super.unit,
    required super.unitCost,
    required super.totalCost,
    super.fromLocation,
    super.toLocation,
    super.reference,
    super.referenceId,
    super.referenceType,
    super.description,
    super.notes,
    required super.movementDate,
    super.processedDate,
    super.processedBy,
    super.metadata,
    required super.createdAt,
    required super.updatedAt,
    super.createdBy,
    super.updatedBy,
  });

  @override
  InventoryMovementModel copyWith({
    String? id,
    String? movementNumber,
    InventoryMovementType? type,
    InventoryMovementStatus? status,
    String? itemId,
    String? itemName,
    String? itemSku,
    double? quantity,
    String? unit,
    double? unitCost,
    double? totalCost,
    String? fromLocation,
    String? toLocation,
    String? reference,
    String? referenceId,
    String? referenceType,
    String? description,
    String? notes,
    DateTime? movementDate,
    DateTime? processedDate,
    String? processedBy,
    Map<String, dynamic>? metadata,
    DateTime? createdAt,
    DateTime? updatedAt,
    String? createdBy,
    String? updatedBy,
  }) {
    return InventoryMovementModel(
      id: id ?? this.id,
      movementNumber: movementNumber ?? this.movementNumber,
      type: type ?? this.type,
      status: status ?? this.status,
      itemId: itemId ?? this.itemId,
      itemName: itemName ?? this.itemName,
      itemSku: itemSku ?? this.itemSku,
      quantity: quantity ?? this.quantity,
      unit: unit ?? this.unit,
      unitCost: unitCost ?? this.unitCost,
      totalCost: totalCost ?? this.totalCost,
      fromLocation: fromLocation ?? this.fromLocation,
      toLocation: toLocation ?? this.toLocation,
      reference: reference ?? this.reference,
      referenceId: referenceId ?? this.referenceId,
      referenceType: referenceType ?? this.referenceType,
      description: description ?? this.description,
      notes: notes ?? this.notes,
      movementDate: movementDate ?? this.movementDate,
      processedDate: processedDate ?? this.processedDate,
      processedBy: processedBy ?? this.processedBy,
      metadata: metadata ?? this.metadata,
      createdAt: createdAt ?? this.createdAt,
      updatedAt: updatedAt ?? this.updatedAt,
      createdBy: createdBy ?? this.createdBy,
      updatedBy: updatedBy ?? this.updatedBy,
    );
  }

  /// Firestore DocumentSnapshot'tan InventoryMovementModel oluşturur
  factory InventoryMovementModel.fromFirestore(DocumentSnapshot doc) {
    final data = doc.data() as Map<String, dynamic>;
    return InventoryMovementModel(
      id: doc.id,
      movementNumber: data['movementNumber'] as String,
      type: InventoryMovementType.values.firstWhere(
        (e) => e.name == data['type'],
        orElse: () => InventoryMovementType.incoming,
      ),
      status: InventoryMovementStatus.values.firstWhere(
        (e) => e.name == data['status'],
        orElse: () => InventoryMovementStatus.pending,
      ),
      itemId: data['itemId'] as String,
      itemName: data['itemName'] as String?,
      itemSku: data['itemSku'] as String?,
      quantity: (data['quantity'] as num).toDouble(),
      unit: data['unit'] as String,
      unitCost: (data['unitCost'] as num).toDouble(),
      totalCost: (data['totalCost'] as num).toDouble(),
      fromLocation: data['fromLocation'] as String?,
      toLocation: data['toLocation'] as String?,
      reference: data['reference'] as String?,
      referenceId: data['referenceId'] as String?,
      referenceType: data['referenceType'] as String?,
      description: data['description'] as String?,
      notes: data['notes'] as String?,
      movementDate: (data['movementDate'] as Timestamp).toDate(),
      processedDate: (data['processedDate'] as Timestamp?)?.toDate(),
      processedBy: data['processedBy'] as String?,
      metadata: Map<String, dynamic>.from(data['metadata'] ?? {}),
      createdAt: (data['createdAt'] as Timestamp).toDate(),
      updatedAt: (data['updatedAt'] as Timestamp).toDate(),
      createdBy: data['createdBy'] as String?,
      updatedBy: data['updatedBy'] as String?,
    );
  }

  /// InventoryMovementModel'i Firestore'a uygun Map'e dönüştürür
  Map<String, dynamic> toFirestore() {
    return {
      'movementNumber': movementNumber,
      'type': type.name,
      'status': status.name,
      'itemId': itemId,
      'itemName': itemName,
      'itemSku': itemSku,
      'quantity': quantity,
      'unit': unit,
      'unitCost': unitCost,
      'totalCost': totalCost,
      'fromLocation': fromLocation,
      'toLocation': toLocation,
      'reference': reference,
      'referenceId': referenceId,
      'referenceType': referenceType,
      'description': description,
      'notes': notes,
      'movementDate': Timestamp.fromDate(movementDate),
      'processedDate':
          processedDate != null ? Timestamp.fromDate(processedDate!) : null,
      'processedBy': processedBy,
      'metadata': metadata,
      'createdAt': Timestamp.fromDate(createdAt),
      'updatedAt': FieldValue.serverTimestamp(),
      'createdBy': createdBy,
      'updatedBy': updatedBy,
    };
  }

  /// InventoryMovementModel'i InventoryMovement entity'sine dönüştürür
  InventoryMovement toEntity() {
    return InventoryMovement(
      id: id,
      movementNumber: movementNumber,
      type: type,
      status: status,
      itemId: itemId,
      itemName: itemName,
      itemSku: itemSku,
      quantity: quantity,
      unit: unit,
      unitCost: unitCost,
      totalCost: totalCost,
      fromLocation: fromLocation,
      toLocation: toLocation,
      reference: reference,
      referenceId: referenceId,
      referenceType: referenceType,
      description: description,
      notes: notes,
      movementDate: movementDate,
      processedDate: processedDate,
      processedBy: processedBy,
      metadata: metadata,
      createdAt: createdAt,
      updatedAt: updatedAt,
      createdBy: createdBy,
      updatedBy: updatedBy,
    );
  }

  /// InventoryMovement entity'sinden InventoryMovementModel oluşturur
  factory InventoryMovementModel.fromEntity(
      InventoryMovement inventoryMovement) {
    return InventoryMovementModel(
      id: inventoryMovement.id,
      movementNumber: inventoryMovement.movementNumber,
      type: inventoryMovement.type,
      status: inventoryMovement.status,
      itemId: inventoryMovement.itemId,
      itemName: inventoryMovement.itemName,
      itemSku: inventoryMovement.itemSku,
      quantity: inventoryMovement.quantity,
      unit: inventoryMovement.unit,
      unitCost: inventoryMovement.unitCost,
      totalCost: inventoryMovement.totalCost,
      fromLocation: inventoryMovement.fromLocation,
      toLocation: inventoryMovement.toLocation,
      reference: inventoryMovement.reference,
      referenceId: inventoryMovement.referenceId,
      referenceType: inventoryMovement.referenceType,
      description: inventoryMovement.description,
      notes: inventoryMovement.notes,
      movementDate: inventoryMovement.movementDate,
      processedDate: inventoryMovement.processedDate,
      processedBy: inventoryMovement.processedBy,
      metadata: inventoryMovement.metadata,
      createdAt: inventoryMovement.createdAt,
      updatedAt: inventoryMovement.updatedAt,
      createdBy: inventoryMovement.createdBy,
      updatedBy: inventoryMovement.updatedBy,
    );
  }
}
