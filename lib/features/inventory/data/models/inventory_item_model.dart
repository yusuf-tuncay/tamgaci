import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:tamgaci/features/inventory/domain/entities/inventory_item.dart';

/// InventoryItem model for Firebase integration
class InventoryItemModel extends InventoryItem {
  const InventoryItemModel({
    required super.id,
    required super.name,
    super.description,
    super.sku,
    super.barcode,
    required super.type,
    required super.status,
    super.category,
    super.brand,
    super.model,
    required super.unit,
    required super.currentStock,
    required super.minimumStock,
    required super.maximumStock,
    required super.reorderPoint,
    required super.reorderQuantity,
    required super.unitCost,
    required super.unitPrice,
    required super.currency,
    super.location,
    super.supplierId,
    super.supplierName,
    super.lastRestocked,
    super.lastSold,
    super.expiryDate,
    super.attributes,
    super.tags,
    super.images,
    required super.createdAt,
    required super.updatedAt,
    super.createdBy,
    super.updatedBy,
  });

  @override
  InventoryItemModel copyWith({
    String? id,
    String? name,
    String? description,
    String? sku,
    String? barcode,
    InventoryItemType? type,
    InventoryItemStatus? status,
    String? category,
    String? brand,
    String? model,
    String? unit,
    double? currentStock,
    double? minimumStock,
    double? maximumStock,
    double? reorderPoint,
    double? reorderQuantity,
    double? unitCost,
    double? unitPrice,
    String? currency,
    String? location,
    String? supplierId,
    String? supplierName,
    DateTime? lastRestocked,
    DateTime? lastSold,
    DateTime? expiryDate,
    Map<String, dynamic>? attributes,
    List<String>? tags,
    List<String>? images,
    DateTime? createdAt,
    DateTime? updatedAt,
    String? createdBy,
    String? updatedBy,
  }) {
    return InventoryItemModel(
      id: id ?? this.id,
      name: name ?? this.name,
      description: description ?? this.description,
      sku: sku ?? this.sku,
      barcode: barcode ?? this.barcode,
      type: type ?? this.type,
      status: status ?? this.status,
      category: category ?? this.category,
      brand: brand ?? this.brand,
      model: model ?? this.model,
      unit: unit ?? this.unit,
      currentStock: currentStock ?? this.currentStock,
      minimumStock: minimumStock ?? this.minimumStock,
      maximumStock: maximumStock ?? this.maximumStock,
      reorderPoint: reorderPoint ?? this.reorderPoint,
      reorderQuantity: reorderQuantity ?? this.reorderQuantity,
      unitCost: unitCost ?? this.unitCost,
      unitPrice: unitPrice ?? this.unitPrice,
      currency: currency ?? this.currency,
      location: location ?? this.location,
      supplierId: supplierId ?? this.supplierId,
      supplierName: supplierName ?? this.supplierName,
      lastRestocked: lastRestocked ?? this.lastRestocked,
      lastSold: lastSold ?? this.lastSold,
      expiryDate: expiryDate ?? this.expiryDate,
      attributes: attributes ?? this.attributes,
      tags: tags ?? this.tags,
      images: images ?? this.images,
      createdAt: createdAt ?? this.createdAt,
      updatedAt: updatedAt ?? this.updatedAt,
      createdBy: createdBy ?? this.createdBy,
      updatedBy: updatedBy ?? this.updatedBy,
    );
  }

  /// Firestore DocumentSnapshot'tan InventoryItemModel oluşturur
  factory InventoryItemModel.fromFirestore(DocumentSnapshot doc) {
    final data = doc.data() as Map<String, dynamic>;
    return InventoryItemModel(
      id: doc.id,
      name: data['name'] as String,
      description: data['description'] as String?,
      sku: data['sku'] as String?,
      barcode: data['barcode'] as String?,
      type: InventoryItemType.values.firstWhere(
        (e) => e.name == data['type'],
        orElse: () => InventoryItemType.product,
      ),
      status: InventoryItemStatus.values.firstWhere(
        (e) => e.name == data['status'],
        orElse: () => InventoryItemStatus.active,
      ),
      category: data['category'] as String?,
      brand: data['brand'] as String?,
      model: data['model'] as String?,
      unit: data['unit'] as String,
      currentStock: (data['currentStock'] as num).toDouble(),
      minimumStock: (data['minimumStock'] as num).toDouble(),
      maximumStock: (data['maximumStock'] as num).toDouble(),
      reorderPoint: (data['reorderPoint'] as num).toDouble(),
      reorderQuantity: (data['reorderQuantity'] as num).toDouble(),
      unitCost: (data['unitCost'] as num).toDouble(),
      unitPrice: (data['unitPrice'] as num).toDouble(),
      currency: data['currency'] as String,
      location: data['location'] as String?,
      supplierId: data['supplierId'] as String?,
      supplierName: data['supplierName'] as String?,
      lastRestocked: (data['lastRestocked'] as Timestamp?)?.toDate(),
      lastSold: (data['lastSold'] as Timestamp?)?.toDate(),
      expiryDate: (data['expiryDate'] as Timestamp?)?.toDate(),
      attributes: Map<String, dynamic>.from(data['attributes'] ?? {}),
      tags: List<String>.from(data['tags'] ?? []),
      images: List<String>.from(data['images'] ?? []),
      createdAt: (data['createdAt'] as Timestamp).toDate(),
      updatedAt: (data['updatedAt'] as Timestamp).toDate(),
      createdBy: data['createdBy'] as String?,
      updatedBy: data['updatedBy'] as String?,
    );
  }

  /// InventoryItemModel'i Firestore'a uygun Map'e dönüştürür
  Map<String, dynamic> toFirestore() {
    return {
      'name': name,
      'description': description,
      'sku': sku,
      'barcode': barcode,
      'type': type.name,
      'status': status.name,
      'category': category,
      'brand': brand,
      'model': model,
      'unit': unit,
      'currentStock': currentStock,
      'minimumStock': minimumStock,
      'maximumStock': maximumStock,
      'reorderPoint': reorderPoint,
      'reorderQuantity': reorderQuantity,
      'unitCost': unitCost,
      'unitPrice': unitPrice,
      'currency': currency,
      'location': location,
      'supplierId': supplierId,
      'supplierName': supplierName,
      'lastRestocked':
          lastRestocked != null ? Timestamp.fromDate(lastRestocked!) : null,
      'lastSold': lastSold != null ? Timestamp.fromDate(lastSold!) : null,
      'expiryDate': expiryDate != null ? Timestamp.fromDate(expiryDate!) : null,
      'attributes': attributes,
      'tags': tags,
      'images': images,
      'createdAt': Timestamp.fromDate(createdAt),
      'updatedAt': FieldValue.serverTimestamp(),
      'createdBy': createdBy,
      'updatedBy': updatedBy,
    };
  }

  /// InventoryItemModel'i InventoryItem entity'sine dönüştürür
  InventoryItem toEntity() {
    return InventoryItem(
      id: id,
      name: name,
      description: description,
      sku: sku,
      barcode: barcode,
      type: type,
      status: status,
      category: category,
      brand: brand,
      model: model,
      unit: unit,
      currentStock: currentStock,
      minimumStock: minimumStock,
      maximumStock: maximumStock,
      reorderPoint: reorderPoint,
      reorderQuantity: reorderQuantity,
      unitCost: unitCost,
      unitPrice: unitPrice,
      currency: currency,
      location: location,
      supplierId: supplierId,
      supplierName: supplierName,
      lastRestocked: lastRestocked,
      lastSold: lastSold,
      expiryDate: expiryDate,
      attributes: attributes,
      tags: tags,
      images: images,
      createdAt: createdAt,
      updatedAt: updatedAt,
      createdBy: createdBy,
      updatedBy: updatedBy,
    );
  }

  /// InventoryItem entity'sinden InventoryItemModel oluşturur
  factory InventoryItemModel.fromEntity(InventoryItem inventoryItem) {
    return InventoryItemModel(
      id: inventoryItem.id,
      name: inventoryItem.name,
      description: inventoryItem.description,
      sku: inventoryItem.sku,
      barcode: inventoryItem.barcode,
      type: inventoryItem.type,
      status: inventoryItem.status,
      category: inventoryItem.category,
      brand: inventoryItem.brand,
      model: inventoryItem.model,
      unit: inventoryItem.unit,
      currentStock: inventoryItem.currentStock,
      minimumStock: inventoryItem.minimumStock,
      maximumStock: inventoryItem.maximumStock,
      reorderPoint: inventoryItem.reorderPoint,
      reorderQuantity: inventoryItem.reorderQuantity,
      unitCost: inventoryItem.unitCost,
      unitPrice: inventoryItem.unitPrice,
      currency: inventoryItem.currency,
      location: inventoryItem.location,
      supplierId: inventoryItem.supplierId,
      supplierName: inventoryItem.supplierName,
      lastRestocked: inventoryItem.lastRestocked,
      lastSold: inventoryItem.lastSold,
      expiryDate: inventoryItem.expiryDate,
      attributes: inventoryItem.attributes,
      tags: inventoryItem.tags,
      images: inventoryItem.images,
      createdAt: inventoryItem.createdAt,
      updatedAt: inventoryItem.updatedAt,
      createdBy: inventoryItem.createdBy,
      updatedBy: inventoryItem.updatedBy,
    );
  }
}
